const fingerSizeTable = [
  { size: "06", circumference: 51.9 },
  { size: "07", circumference: 54.4 },
  { size: "08", circumference: 57.0 },
  { size: "09", circumference: 59.5 },
  { size: "10", circumference: 62.1 },
];
const fingerForm = document.querySelector(".finger-size-tool");
let suggestedRingSize = "";
const circumferenceInput = document.querySelector("#finger-circumference");

function renderFingerSizeResult() {
  const circumference = Number(circumferenceInput.value);
  const result = document.querySelector(".finger-result");
  const applyButton = document.querySelector(".apply-finger-size");
  const minimum = fingerSizeTable[0].circumference;
  const maximum = fingerSizeTable[fingerSizeTable.length - 1].circumference;
  suggestedRingSize = "";
  applyButton.hidden = true;

  if (!Number.isFinite(circumference) || circumference <= 0) {
    result.textContent = window.AGON_I18N.t("Vui lòng nhập chu vi ngón tay hợp lệ (mm).");
    return;
  }
  if (circumference < minimum || circumference > maximum) {
    result.textContent = window.AGON_I18N.t("Số đo {measure} mm nằm ngoài phạm vi size US 06–10 ({minimum}–{maximum} mm). Vui lòng liên hệ AGON để được tư vấn size phù hợp.")
      .replace("{measure}", circumference)
      .replace("{minimum}", minimum)
      .replace("{maximum}", maximum);
    return;
  }

  const nearest = fingerSizeTable.reduce((best, option) =>
    Math.abs(option.circumference - circumference) < Math.abs(best.circumference - circumference) ? option : best,
  );
  suggestedRingSize = nearest.size;
  result.textContent = window.AGON_I18N.t("Chu vi {measure} mm phù hợp nhất với size US {size} (chu vi tham chiếu {reference} mm).")
    .replace("{measure}", circumference)
    .replace("{size}", nearest.size)
    .replace("{reference}", nearest.circumference.toFixed(1));
  applyButton.hidden = false;
}

fingerForm.addEventListener("submit", (event) => {
  event.preventDefault();
  renderFingerSizeResult();
});
window.addEventListener("agon-language-change", () => {
  if (circumferenceInput.value) renderFingerSizeResult();
});

document.querySelector(".apply-finger-size").addEventListener("click", () => {
  const sizeButton = document.querySelector(`.size-options button[data-size="${suggestedRingSize}"]`);
  if (!sizeButton) return;
  sizeButton.click();
  showToast(window.AGON_I18N.t("Đã chọn size US {size}.").replace("{size}", suggestedRingSize));
});

