const normalize = (value) => value.replace(/\s+/g, " ").trim();
const viToEnNormalized = new Map(Object.entries(viToEn).map(([vietnamese, english]) => [normalize(vietnamese), english]));
const enToVi = new Map(Object.entries(viToEn).map(([vietnamese, english]) => [normalize(english), vietnamese]));
const languageKey = "agon-language";
let language = localStorage.getItem(languageKey) === "en" ? "en" : "vi";

function translate(value) {
  const key = normalize(value);
  return language === "en" ? viToEnNormalized.get(key) || value : enToVi.get(key) || value;
}

function translatePage() {
  document.documentElement.lang = language;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const text = node.nodeValue.trim();
    if (text) {
      const translated = translate(text);
      if (translated !== text) {
        const leading = node.nodeValue.match(/^\s*/)[0];
        const trailing = node.nodeValue.match(/\s*$/)[0];
        node.nodeValue = `${leading}${translated}${trailing}`;
      }
    }
  }
  document.querySelectorAll("[placeholder]").forEach((element) => {
    element.placeholder = translate(element.placeholder);
  });
  document.querySelectorAll("[aria-label]").forEach((element) => {
    element.setAttribute("aria-label", translate(element.getAttribute("aria-label")));
  });
  document.title = translate(document.title);
  const toggle = document.querySelector(".language-toggle");
  toggle.textContent = language === "vi" ? "EN" : "VI";
  toggle.setAttribute("aria-label", language === "vi" ? "Switch language to English" : "Chuyển sang Tiếng Việt");
  window.dispatchEvent(new CustomEvent("agon-language-change", { detail: { language } }));
}

window.AGON_I18N = {
  get language() {
    return language;
  },
  t: translate,
  setLanguage(nextLanguage) {
    language = nextLanguage === "en" ? "en" : "vi";
    localStorage.setItem(languageKey, language);
    translatePage();
  },
};

document.querySelector(".language-toggle").addEventListener("click", () => {
  window.AGON_I18N.setLanguage(language === "vi" ? "en" : "vi");
});
document.addEventListener("DOMContentLoaded", translatePage);
